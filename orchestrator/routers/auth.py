# Validate Session
# ==========================================================

@router.get("/validate-session")
async def validate_session(
    current_user: dict = Depends(get_current_user),
):
    """
    Lightweight endpoint used by the frontend to verify
    that the JWT cookie is still valid.

    Useful during initial page load or app refresh.
    """

    return {
        "authenticated": True,
        "user": {
            "id": current_user["id"],
            "username": current_user["username"],
            "email": current_user["email"],
        },
    }